"""Export every number quoted in the manuscript.

The manuscript never contains hand-typed results. Each figure is stored once in
results/numbers.json and exposed to LaTeX as a macro in manuscript/generated/numbers.tex,
e.g. ``\\NEventsTotal`` -> 43440.

Keys must be letters only (LaTeX macro names cannot contain digits or underscores).
"""
from __future__ import annotations

import json
import re
from pathlib import Path

_KEY = re.compile(r"[A-Za-z]+")


def _check_key(key: str) -> None:
    if not _KEY.fullmatch(key):
        raise ValueError(f"Number key '{key}' must contain letters only")


def write_numbers(numbers: dict, json_path: str | Path, tex_path: str | Path) -> None:
    for key in numbers:
        _check_key(key)
    json_path, tex_path = Path(json_path), Path(tex_path)
    json_path.parent.mkdir(parents=True, exist_ok=True)
    tex_path.parent.mkdir(parents=True, exist_ok=True)

    existing = {}
    if json_path.exists():
        existing = json.loads(json_path.read_text(encoding="utf-8"))
    existing.update(numbers)
    ordered = dict(sorted(existing.items()))
    json_path.write_text(json.dumps(ordered, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    lines = ["% Generated by cmerate.numbers from results/numbers.json -- do not edit by hand."]
    for key, value in ordered.items():
        lines.append(f"\\newcommand{{\\{key}}}{{{value}}}")
    tex_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
